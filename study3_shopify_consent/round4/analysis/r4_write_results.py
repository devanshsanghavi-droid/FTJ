"""Write round4/analysis/stats_r4.json and RESULTS_R4.md. Every number in RESULTS_R4.md is rendered by N() from a key
in stats_r4.json and recorded in outputs/number_registry_r4.csv, which r4_trace_check.py re-renders and checks.
Inputs: outputs/blocklist_r4.json (r4_blocklist.py combine), outputs/beyond/beyond_r4.json (r4_beyond.py),
round4/<set>/crawl/logs/crawl_status.jsonl and plan_r4.json (crawl provenance)."""
import csv
import json
import os
from datetime import datetime, timezone

HERE = os.path.dirname(os.path.abspath(__file__))
STUDY = os.path.normpath(os.path.join(HERE, '..', '..'))
R4 = os.path.join(STUDY, 'round4')
OUTS = os.path.join(HERE, 'outputs')
REG = []


def crawl_meta(set_):
    d = os.path.join(R4, set_, 'crawl')
    out = dict(raw_files=0, loads_logged=0)
    if os.path.isdir(os.path.join(d, 'raw')):
        out['raw_files'] = len([f for f in os.listdir(os.path.join(d, 'raw')) if f.endswith('.json.gz')])
    sl = os.path.join(d, 'logs', 'crawl_status.jsonl')
    if os.path.exists(sl):
        rows = [json.loads(x) for x in open(sl) if x.strip()]
        out['loads_logged'] = len(rows)
        if rows:
            out['first_load_utc'] = min(r['at'] for r in rows)
            out['last_load_utc'] = max(r['at'] for r in rows)
    pf = os.path.join(d, 'plan_r4.json')
    if os.path.exists(pf):
        P = json.load(open(pf))['sites']
        out['sites_planned'] = len(P)
        dec = {}
        for p in P:
            dec[p.get('decision')] = dec.get(p.get('decision'), 0) + 1
        out['decisions'] = dec
        out['sites_loaded'] = sum(1 for p in P if p.get('load_url'))
        out['untagged_urls'] = sum(1 for p in P if p.get('decision', '').startswith('load_plain'))
        src = {}
        for p in P:
            src[p.get('product_url_source')] = src.get(p.get('product_url_source'), 0) + 1
        out['page_source'] = src
    try:
        s = os.statvfs(d)
        out['free_gb_at_write'] = round(s.f_bavail * s.f_frsize / 1e9, 2)
    except Exception:
        pass
    du = 0
    for root, _, files in os.walk(d):
        for f in files:
            du += os.path.getsize(os.path.join(root, f))
    out['disk_mb'] = round(du / 1e6, 1)
    return out


def get(S, key):
    cur = S
    for p in key.split('/'):
        cur = cur[int(p)] if isinstance(cur, list) else cur[p]
    return cur


def render(v, f):
    if f == 'int':
        return f'{int(round(v)):,}'
    if f == 'pct0':
        return f'{100 * v:.0f}'
    if f == 'pct1':
        return f'{100 * v:.1f}'
    if f == 'pp1':
        return f'{100 * v:+.1f}'
    if f.startswith('f'):
        return f'{v:.{int(f[1:])}f}'
    return str(v)


def mk(S):
    def N(key, f='int'):
        v = get(S, key)
        s = render(v, f)
        REG.append(dict(text=s, key=key, fmt=f, value=json.dumps(v)))
        return s

    def P(key, boot=True):
        s = f"{N(key + '/k')}/{N(key + '/n')} = {N(key + '/p', 'pct1')}% (Wilson 95% CI {N(key + '/lo', 'pct1')}–{N(key + '/hi', 'pct1')}"
        r = get(S, key)
        if boot and r.get('boot_lo') is not None:
            s += f"; store bootstrap {N(key + '/boot_lo', 'pct1')}–{N(key + '/boot_hi', 'pct1')}"
        return s + ')'

    def D(key):
        return f"{N(key + '/diff', 'pp1')} points (95% CI {N(key + '/diff_lo', 'pp1')} to {N(key + '/diff_hi', 'pp1')})"

    def MH(key):
        return (f"{N(key + '/rd', 'pp1')} points (95% CI {N(key + '/rd_lo', 'pp1')} to {N(key + '/rd_hi', 'pp1')}; "
                f"{N(key + '/k1')}/{N(key + '/n1')} blocklist vs {N(key + '/k0')}/{N(key + '/n0')} reference stores)")
    return N, P, D, MH


def main():
    BL = json.load(open(os.path.join(OUTS, 'blocklist_r4.json')))
    bf = os.path.join(OUTS, 'beyond', 'beyond_r4.json')
    BY = json.load(open(bf)) if os.path.exists(bf) else None
    main_stats = json.load(open(os.path.join(STUDY, 'analysis', 'outputs', 'stats.json')))
    S = dict(generated_utc=datetime.now(timezone.utc).strftime('%Y-%m-%dT%H:%MZ'), crawl=dict(expansion=crawl_meta('expansion'), beyond=crawl_meta('beyond')),
             blocklist=BL, beyond=BY,
             main_paper=dict(primary=main_stats['fig4']['a']['blocklist']['primary']['fired'], unconditioned=main_stats['fig4']['a']['blocklist']['declared_vendor_fired_sbx'],
                             mh_no_yes=main_stats['fig4']['a']['like_for_like']['mh_no_yes']))
    json.dump(S, open(os.path.join(HERE, 'stats_r4.json'), 'w'), indent=1, default=str)
    N, P, D, MH = mk(S)
    t = []
    a = t.append
    a('# Round 4 results: expanded blocklist stratum (B1) and beyond-Shopify pilot (B2)\n')
    a(f"Generated by `r4_write_results.py` from `stats_r4.json` ({S['generated_utc']}); every number below is registered in "
      "`outputs/number_registry_r4.csv` and checked by `r4_trace_check.py`. RESTRICTED inputs (domains) stay in `outputs/`; this file names no site.\n")
    a('## 1. What was measured\n')
    ce, cb = S['crawl']['expansion'], S['crawl']['beyond']
    if ce.get('sites_planned'):
        a(f"- **B1 expansion (Shopify, Tranco 200k–1M).** {N('crawl/expansion/sites_planned')} candidate stores; "
          f"{N('crawl/expansion/sites_loaded')} passed the robots.txt check and were loaded ({N('crawl/expansion/untagged_urls')} without the test code because robots.txt disallowed the tagged address); "
          f"{N('crawl/expansion/raw_files')} load records.")
    if cb.get('sites_planned'):
        a(f"- **B2 beyond-Shopify.** {N('crawl/beyond/sites_planned')} selected sites; {N('crawl/beyond/sites_loaded')} loaded; {N('crawl/beyond/raw_files')} load records.")
    a("- Method: `crawl/crawl.js` run unchanged through `round4/expansion/crawl/crawl_r4.js` (plan and output substitutions; for B2 also first-party URL/body retention, Set-Cookie names and architecture readouts). "
      "Arms A0 Default, A1 Decline only (then one reload), A2 GPC injected in every frame and worker. Fresh profile per load, default headless UA, robots.txt checked before the first load, "
      "at most 6 browsers, at least 10 s between loads of a site and 1 s between navigations.\n")
    # ---------------- B1
    a('## 2. Blocked on paper (B1)\n')
    a("Definitions are the main paper's (analysis/analyze.py): a blocklist store's CMP configuration, read at run time in the Default load, declares an advertising vendor blocked before any choice; "
      "it FIRED if that vendor sent a request from Shopify's sandbox in the Default load. PRIMARY = stores whose CMP wrote no 'marketing: yes' without a click. "
      "The main-sample numbers below are recomputed by the Round 4 code and equal the paper's (trace check 3).\n")
    for ds, lab in (('main', 'Main sample (Part A)'), ('expansion', 'Expansion (ranks 200k–1M)'), ('combined', 'Combined')):
        if ds not in BL:
            continue
        k = f'blocklist/{ds}'
        a(f"### {lab}\n")
        a(f"- Blocklist stores at run time: {N(k + '/n_blocklist')}; CMP wrote 'yes' without a click: {N(k + '/yes_writers/n')} (automatic grants {N(k + '/yes_writers/auto_grant')}).")
        a(f"- Declared-blocked vendor fired from the sandbox, all blocklist stores: {P(k + '/unconditioned/fired')}.")
        a(f"- **PRIMARY (no 'yes' write), declared vendor fired:** {P(k + '/primary/fired')}; marketing-declaring pixel: {P(k + '/primary/fired_mkt')}; any sandboxed ad request: {P(k + '/primary/any_sbx')}.")
        a(f"- Primary by Shopify's region default: allowed {N(k + '/primary/by_default/allowed/k')}/{N(k + '/primary/by_default/allowed/n')}, denied {N(k + '/primary/by_default/denied/k')}/{N(k + '/primary/by_default/denied/n')}.")
        a(f"- Entry level (store × declared-blocked vendor pairs, primary stores): {N(k + '/pairs/primary/k')}/{N(k + '/pairs/primary/n')} fired = {N(k + '/pairs/primary/p', 'pct1')}% "
          f"(store-cluster bootstrap {N(k + '/pairs/primary/cboot_lo', 'pct1')}–{N(k + '/pairs/primary/cboot_hi', 'pct1')}).")
        if BL[ds]['primary'].get('fired_design_weighted'):
            a(f"- Design-weighted primary rate (sensitivity): {N(k + '/primary/fired_design_weighted/p', 'pct1')}% (stratified bootstrap {N(k + '/primary/fired_design_weighted/lo', 'pct1')}–{N(k + '/primary/fired_design_weighted/hi', 'pct1')}).")
        lf = BL[ds]['like_for_like']
        a(f"- Like-for-like (any sandboxed ad request, blocklist vs main-sample banner stores without a declared-blocked vendor), Mantel–Haenszel over the region default: all stores {MH(k + '/like_for_like/mh')}; "
          f"no-'yes' stores {MH(k + '/like_for_like/mh_no_yes')}. A blocklist that reduced sandboxed firing would give a negative difference; "
          f"the no-'yes' comparison rules out a reduction larger than {N(k + '/like_for_like/mh_no_yes/reduction_ruled_out_beyond', 'pct1')} points.")
        for dl in ('allowed', 'denied'):
            if lf[dl + '_no_yes']['blocklist']['n']:
                a(f"  - {dl} default, no-'yes': blocklist {P(k + f'/like_for_like/{dl}_no_yes/blocklist', boot=False)} vs reference {P(k + f'/like_for_like/{dl}_no_yes/reference', boot=False)}; "
                  f"difference {D(k + f'/like_for_like/{dl}_no_yes/diff')}.")
        a('')
    if 'main_vs_expansion_primary' in BL:
        a(f"**How the result changed.** The paper's primary estimate rested on {N('main_paper/primary/n')} stores ({N('main_paper/primary/p', 'pct1')}%, CI {N('main_paper/primary/lo', 'pct1')}–{N('main_paper/primary/hi', 'pct1')}). "
          f"With the expansion the primary sample is {N('blocklist/combined/primary/n')} stores: {N('blocklist/combined/primary/fired/p', 'pct1')}% (CI {N('blocklist/combined/primary/fired/lo', 'pct1')}–{N('blocklist/combined/primary/fired/hi', 'pct1')}). "
          f"Expansion minus main: {D('blocklist/main_vs_expansion_primary')}; Fisher exact p = {N('blocklist/main_vs_expansion_primary/fisher_p', 'f3')}.\n")
        fu = BL.get('expansion_funnel') or {}
        if fu:
            a(f"Expansion funnel: {N('blocklist/expansion_funnel/candidates')} candidates, {N('blocklist/expansion_funnel/captured_all_three')} captured in all three arms, "
              f"{N('blocklist/expansion_funnel/blocklist_at_runtime')} with the blocklist in force at run time (static 'yes' confirmed {N('blocklist/expansion_funnel/static_yes_confirmed/k')}/{N('blocklist/expansion_funnel/static_yes_confirmed/n')}, "
              f"'unknown' {N('blocklist/expansion_funnel/static_unknown_confirmed/k')}/{N('blocklist/expansion_funnel/static_unknown_confirmed/n')}).\n")
    # ---------------- B2
    a('## 3. Beyond Shopify (B2)\n')
    if not BY or not BY.get('rates'):
        a('No B2 measurement data yet.\n')
    else:
        a("Rates are per selected site (a pilot, not population estimates). 'Ad request' = a request to an advertising vendor, or a first-party hit whose wire format names Google Ads, Meta or TikTok "
          "(PROTOCOL.md 4). 'First-party collect' = any strong first-party beacon (GA4, Google Ads, UA, Meta, TikTok, Zaraz). Server-side forwarding is not observable and is never inferred.\n")
        a('| Setup | Sites (ok Default) | Banner seen | Ad request before any choice (banner sites) | Ad request after a working Decline | Ad request under GPC vs Default |')
        a('|---|---|---|---|---|---|')
        for arch, lab in (('wix', 'Wix'), ('bigcommerce', 'BigCommerce'), ('gateway', 'First-party gateway')):
            k = f'beyond/rates/{arch}'
            r = BY['rates'][arch]
            g = r.get('gpc')
            gs = f"{N(k + '/gpc/A2_ad/k')}/{N(k + '/gpc/A2_ad/n')} vs {N(k + '/gpc/A0_ad/k')}/{N(k + '/gpc/A0_ad/n')} (McNemar p = {N(k + '/gpc/mcnemar/p_exact', 'f3')})" if g else '–'
            dec = f"{N(k + '/decline/after_ad/k')}/{N(k + '/decline/after_ad/n')}" + (f" ({N(k + '/decline/after_ad/p', 'pct0')}%, CI {N(k + '/decline/after_ad/lo', 'pct0')}–{N(k + '/decline/after_ad/hi', 'pct0')})" if r['decline']['after_ad']['n'] else '')
            pre = f"{N(k + '/prechoice_ad_banner/k')}/{N(k + '/prechoice_ad_banner/n')}" + (f" ({N(k + '/prechoice_ad_banner/p', 'pct0')}%, CI {N(k + '/prechoice_ad_banner/lo', 'pct0')}–{N(k + '/prechoice_ad_banner/hi', 'pct0')})" if r['prechoice_ad_banner']['n'] else '')
            a(f"| {lab} | {N(k + '/n_A0')} | {N(k + '/banner/k')} | {pre} | {dec} | {gs} |")
        a('')
        for arch, lab in (('wix', 'Wix'), ('bigcommerce', 'BigCommerce'), ('gateway', 'First-party gateway')):
            k = f'beyond/rates/{arch}'
            r = BY['rates'][arch]
            a(f"### {lab}\n")
            a(f"- All sites, ad request before any choice: {P(k + '/prechoice_ad_all')}; banner sites: {P(k + '/prechoice_ad_banner')}; beacons only (banner sites): {P(k + '/prechoice_ad_beacon_banner')}.")
            a(f"- Banner sites with an ad request from outside the top frame's main thread (iframe or worker): {P(k + '/prechoice_ad_offmain_banner')}.")
            a(f"- First-party collect before any choice: all sites {P(k + '/prechoice_fp_collect_all')}.")
            dd = r['decline']
            a(f"- Decline: banner found in the Decline arm on {N(k + '/decline/banner_found/k')}/{N(k + '/decline/banner_found/n')}; no first-layer Decline on {N(k + '/decline/no_decline_option')}; working click on {N(k + '/decline/click_ok')}. "
              + (f"After a working Decline: ad request {P(k + '/decline/after_ad')}; on the fresh page {P(k + '/decline/next_page_ad')}; first-party collect {P(k + '/decline/after_fp_collect')}; "
                 f"server-set identifier cookie on a first-party response {P(k + '/decline/after_server_id_cookie')}." if dd['click_ok'] else ''))
