#!/usr/bin/env python3
"""Build and verify the flat Editorial Manager (EM) submission folder ../submission/.

Run after ./build.sh (it needs main.aux, supplement.aux, main.bbl, main.pdf and supplement.pdf of the same build);
./build.sh flat calls it. Steps:
  1. main.tex: inline the preamble, front matter, sections, generated tables and back matter into one file;
     resolve the references to the supplement (\\ref*{S:...}) to the numbers printed in supplement.pdf;
     rename the figures fig1.pdf ... fig6.pdf in order of their figure numbers; drop \\graphicspath.
  2. copy main.bbl, refs.bib, elsarticle.cls and elsarticle-harv.bst (the versions the build uses), the six figures,
     highlights.txt and supplement.pdf into the folder (no subfolders).
  3. check pdfLaTeX compatibility statically (ASCII only, no XeTeX/LuaTeX-only packages or primitives,
     figure PDF versions <= 1.5), because no pdfLaTeX is installed here.
  4. copy the folder to a fresh directory, compile main.tex there with tectonic, and compare the result with
     this build's main.pdf page by page (page count, extracted text, rendered pixels at 110 dpi): run 1 from the bare
     folder, run 2 from run 1's .aux and .bbl, run 3 a single TeX pass (see the note printed for run 1);
     check that BibTeX on the shipped refs.bib reproduces the shipped main.bbl; check that the strict switch
     (\\def\\SUBMISSION{1}) still stops on the open [AUTHORS] items.
  5. put the verified main.pdf into the folder (the 'Manuscript' PDF for a Your-Paper-Your-Way first submission).
The folder's README_SUBMISSION.md is written by hand and is not touched here.
Usage: python3 make_submission.py [--testdir DIR]
"""
import argparse, glob, hashlib, os, re, shutil, subprocess, sys, tempfile

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.normpath(os.path.join(HERE, '..', 'submission'))
ROOT = os.path.normpath(os.path.join(HERE, '..', '..'))
TECTONIC = os.environ.get('TECTONIC') or shutil.which('tectonic') or 'tectonic'   # release: tectonic on PATH
RENDER = os.path.join(HERE, 'tools', 'pdfpages2png')
os.chdir(HERE)

problems = []
def check(ok, msg):
    print(('  ok   ' if ok else '  FAIL ') + msg)
    if not ok:
        problems.append(msg)

def sha(path):
    return hashlib.sha256(open(path, 'rb').read()).hexdigest()

# ---------------------------------------------------------------- 1. flatten main.tex
def split_comment(line):
    """(code, comment): the comment starts at the first % not escaped by an odd number of backslashes."""
    i = 0
    while True:
        j = line.find('%', i)
        if j < 0:
            return line, ''
        k, bs = j - 1, 0
        while k >= 0 and line[k] == '\\':
            bs += 1; k -= 1
        if bs % 2 == 0:
            return line[:j], line[j:]
        i = j + 1

def labels(aux):
    """\\newlabel{key}{{number}{page}...} -> {key: number}; the number is the first balanced group."""
    out = {}
    for line in open(aux):
        m = re.match(r'\\newlabel\{([^}]*)\}\{\{', line)
        if not m:
            continue
        i, d, j = m.end(), 1, m.end()
        while d:
            d += {'{': 1, '}': -1}.get(line[j], 0); j += 1
        out[m.group(1)] = line[i:j - 1]
    return out

SUPP = labels('supplement.aux')
MAIN = labels('main.aux')
inlined = []

def read_source(name):
    path = name if name.endswith('.tex') else name + '.tex'
    inlined.append(path)
    return open(path, encoding='ascii').read()

def flatten(text, depth=0):
    out = []
    for line in text.split('\n'):
        code, comment = split_comment(line)
        m = re.fullmatch(r'(\s*)\\(input|tabinput)\{([^}]+)\}\s*', code)
        if m:
            name = m.group(3)
            body = flatten(read_source(name), depth + 1).rstrip('\n')
            if m.group(2) == 'input':
                out.append('% ---- inlined from ' + (name if name.endswith('.tex') else name + '.tex') + ' ----')
            out.append(body)
            continue
        if code.strip() == '\\makeatletter\\newcommand{\\tabinput}[1]{\\@@input #1 }\\makeatother':
            # the generated table bodies are inlined, so the preamble's \tabinput helper is not needed
            out.append('% (\\tabinput is not defined here: the generated table bodies are inlined)')
            continue
        if re.search(r'\\(input|include|tabinput)\b', code):
            raise SystemExit('unhandled \\input in line: ' + line)
        out.append(line)
    return '\n'.join(out)

main = open('main.tex', encoding='ascii').read()
# replace main.tex's own header comment (build instructions for the paper folder) with one for the flat file
body = main.split('\\documentclass', 1)[1]
HEADER = r"""% main.tex -- Computers & Security (Elsevier) manuscript: single flat source file for Editorial Manager.
% Generated by paper/make_submission.py (./build.sh flat) from the paper's source files: the preamble, front matter,
% sections, generated tables and back matter are inlined, so this file needs no \input. To change the text, edit the
% sources in paper/ and regenerate; the folder was verified to reproduce the review build page for page.
% Engines: pdfLaTeX (Editorial Manager) and XeTeX (tectonic, used for testing). Standard fonts only (lmodern, T1),
% ASCII only, no fontspec. Needs in the same folder: fig1.pdf ... fig6.pdf, elsarticle.cls, and either main.bbl
% (no BibTeX run) or refs.bib + elsarticle-harv.bst (BibTeX run); both routes give the same reference list.
% References to the supplement (Note S1, Fig. S1, Table S1, ...) are written as fixed numbers that match supplement.pdf.
%
% Open items for the author (\todo) print as red text. When none is left, make_submission.py switches the next line on
% (strict mode: any \todo then stops the compilation with an error). Square-bracketed text such as [Student name] is a
% placeholder for the author to fill in, not a \todo.
%\def\SUBMISSION{1}
"""
flat = flatten(HEADER + '\\documentclass' + body)

# The remaining rewrites touch code only, never comments (the preamble's comments quote some of these commands).
unresolved, figmap, counts = [], {}, {'gp': 0, 'xref': 0, 'ext': 0}
def xref(m):
    counts['xref'] += 1
    if m.group(1) not in SUPP:
        unresolved.append(m.group(1)); return m.group(0)
    return SUPP[m.group(1)]
def fig(m):
    # figures are renamed in order of appearance; checked against the figure numbers of the build (main.aux) below
    if m.group(2) not in figmap:
        figmap[m.group(2)] = 'fig%d.pdf' % (len(figmap) + 1)
    return m.group(1) + figmap[m.group(2)] + '}'
lines = []
for line in flat.split('\n'):
    code, comment = split_comment(line)
    if code.strip() == '\\externaldocument[S:]{supplement}':
        counts['ext'] += 1; continue                      # Editorial Manager compiles the manuscript on its own
    if code.strip() == '\\graphicspath{{figs/}}':
        counts['gp'] += 1; lines.append('% (no \\graphicspath: the figures sit next to main.tex)'); continue
    code = re.sub(r'\\ref\*\{S:([^}]*)\}', xref, code)
    code = re.sub(r'(\\includegraphics(?:\[[^\]]*\])?\{)([^}]+)\}', fig, code)
    lines.append(code + comment)
flat = '\n'.join(lines)
code = '\n'.join(split_comment(l)[0] for l in flat.split('\n'))

n_todo = len(re.findall(r'\\todo\{', code))
if n_todo == 0:
    # 2026-09-28: no open \todo left, so the flat file is built in strict mode (\def\SUBMISSION{1} switched on)
    flat = flat.replace('%\\def\\SUBMISSION{1}', '\\def\\SUBMISSION{1}', 1)
    code = '\n'.join(split_comment(l)[0] for l in flat.split('\n'))
print('1. flatten')
print('   inlined:', ', '.join(inlined))
check(counts['gp'] == 1 and counts['ext'] == 1, '\\graphicspath and \\externaldocument removed')
check(not unresolved, '%d references to the supplement resolved to fixed numbers%s'
      % (counts['xref'], (' (unresolved: %s)' % unresolved) if unresolved else ''))
check(not re.search(r'\{[SM]:', code), 'no cross-document reference left')
check(not re.search(r'\\(input|include|tabinput)\b', code), 'no \\input, \\include or \\tabinput left (outside comments)')
# figure k in the text must carry label number k in main.aux
order = re.findall(r'\\includegraphics(?:\[[^\]]*\])?\{(fig\d+)\.pdf\}.*?\\label\{([^}]+)\}', flat, re.S)
check([MAIN.get(lab) for _, lab in order] == [f[3:] for f, _ in order] and len(order) == 6,
      'figure files match figure numbers: ' + ', '.join('%s=%s' % (f, lab) for f, lab in order))

# ---------------------------------------------------------------- 2. assemble the folder
print('2. assemble', OUT)
keep = {'README_SUBMISSION.md'}
os.makedirs(OUT, exist_ok=True)
for f in os.listdir(OUT):
    if f not in keep:
        p = os.path.join(OUT, f)
        if os.path.isdir(p):
            raise SystemExit('unexpected subfolder in submission/: ' + f)
        os.remove(p)
open(os.path.join(OUT, 'main.tex'), 'w', encoding='ascii').write(flat)
for src, dst in figmap.items():
    shutil.copyfile(os.path.join('figs', src), os.path.join(OUT, dst))
for f in ('main.bbl', 'refs.bib', 'elsarticle.cls', 'elsarticle-harv.bst', 'highlights.txt', 'supplement.pdf'):
    shutil.copyfile(f, os.path.join(OUT, f))
check(all(not os.path.isdir(os.path.join(OUT, f)) for f in os.listdir(OUT)), 'folder is flat')

# ---------------------------------------------------------------- 3. static pdfLaTeX checks
print('3. pdfLaTeX compatibility (static)')
for f in ('main.tex', 'main.bbl', 'refs.bib', 'highlights.txt'):
    data = open(os.path.join(OUT, f), 'rb').read()
    check(all(b < 128 for b in data), f + ' is pure ASCII')
bad_pkgs = ['fontspec', 'unicode-math', 'polyglossia', 'xltxtra', 'xunicode', 'mathspec', 'luacode', 'luatextra',
            'xeCJK', 'realscripts', 'metalogo']
pkgs = set()
for m in re.finditer(r'\\(?:usepackage|RequirePackage)(?:\[[^\]]*\])?\{([^}]+)\}', code):
    pkgs.update(p.strip() for p in m.group(1).split(','))
print('   packages:', ', '.join(sorted(pkgs)))
check(not (pkgs & set(bad_pkgs)), 'no XeTeX/LuaTeX-only package')
check(not re.search(r'\\(XeTeX\w*|directlua|luaexec|setmainfont|setsansfont|setmonofont|newfontfamily)\b', code),
      'no XeTeX/LuaTeX primitives or fontspec commands')
check('\\usepackage[T1]{fontenc}' in code and ('\\usepackage{lmodern}' in code or re.search(r'\\documentclass\[[^\]]*\btimes\b', code)),
      'standard fonts: T1 encoding with lmodern or elsarticle\'s times option (two-column journal layout, 2026-10-06)')
check('\\usepackage[expansion=false]{microtype}' in code, 'microtype without font expansion (same line breaks in both engines)')
for f in sorted(figmap.values()):
    head = open(os.path.join(OUT, f), 'rb').read(9).decode('latin-1')
    check(head.startswith('%PDF-1.') and int(head[7]) <= 5, '%s is %s (pdfTeX accepts up to 1.5 without a warning)' % (f, head[1:8]))
cls = open(os.path.join(OUT, 'elsarticle.cls')).read()
check('\\def\\RCSversion{3.3}' in cls, 'elsarticle.cls is v3.3, the version of the review build')

# ---------------------------------------------------------------- 4. fresh-copy compile and comparison
ap = argparse.ArgumentParser(); ap.add_argument('--testdir'); args = ap.parse_args()
test = args.testdir or tempfile.mkdtemp(prefix='submission_test_')
fresh = os.path.join(test, 'fresh')
shutil.rmtree(fresh, ignore_errors=True)
shutil.copytree(OUT, fresh)
if os.path.exists(os.path.join(fresh, 'README_SUBMISSION.md')):
    os.remove(os.path.join(fresh, 'README_SUBMISSION.md'))
print('4. fresh compile in', fresh)
from pypdf import PdfReader
from PIL import Image, ImageChops
ref_pdf = os.path.join(HERE, 'main.pdf')
newest = max(os.path.getmtime(f) for f in inlined + ['main.tex'] + ['figs/' + s for s in figmap])
check(os.path.getmtime(ref_pdf) >= newest, 'the review build main.pdf is newer than every source it was built from')
check(os.path.getmtime('supplement.pdf') >= max(os.path.getmtime(f) for f in ('supplement.tex', 'preamble.tex', 'main.aux')),
      'supplement.pdf is from the same build (newer than supplement.tex, preamble.tex and main.aux)')
def tectonic(cwd, *extra):
    return subprocess.run([TECTONIC, '--keep-logs', '--keep-intermediates', '--chatter', 'minimal', *extra, 'main.tex'],
                          cwd=cwd, capture_output=True, text=True)
def compare(pdf, tag):
    """(page counts, pages whose extracted text differs, pages whose 110-dpi rendering differs) against the review build"""
    a, b = PdfReader(ref_pdf), PdfReader(pdf)
    text = [i + 1 for i in range(min(len(a.pages), len(b.pages))) if a.pages[i].extract_text() != b.pages[i].extract_text()]
    rd = os.path.join(test, 'render_' + tag); shutil.rmtree(rd, ignore_errors=True); os.makedirs(rd)
    if not os.path.exists(os.path.join(test, 'render_review', 'r-p01.png')):
        os.makedirs(os.path.join(test, 'render_review'), exist_ok=True)
        subprocess.run([RENDER, ref_pdf, os.path.join(test, 'render_review', 'r'), '110'], capture_output=True)
    subprocess.run([RENDER, pdf, os.path.join(rd, 'r'), '110'], capture_output=True)
    pix = []
    for i in range(1, max(len(a.pages), len(b.pages)) + 1):
        p, q = os.path.join(test, 'render_review', 'r-p%02d.png' % i), os.path.join(rd, 'r-p%02d.png' % i)
        if not (os.path.exists(p) and os.path.exists(q)):
            pix.append(i); continue
        x, y = Image.open(p).convert('RGB'), Image.open(q).convert('RGB')
        if x.size != y.size or ImageChops.difference(x, y).getbbox():
            pix.append(i)
    return (len(a.pages), len(b.pages)), text, pix

# Run 1 starts from the bare folder (no .aux): tectonic makes three TeX passes plus BibTeX inside one process.
r = tectonic(fresh)
check(r.returncode == 0, 'run 1 (empty folder): tectonic exit code 0')
log = open(os.path.join(fresh, 'main.log'), errors='replace').read()
check(not re.search(r'undefined|Undefined', log), 'run 1: no undefined references or citations in main.log')
check('Rerun to get' not in log, 'run 1: no rerun request in main.log')
absolute = [l for l in (r.stderr + r.stdout).splitlines() if 'accessing absolute path' in l]
check(not absolute, 'run 1: no file read from outside the folder')
m = re.search(r'Document Class: (elsarticle [^\n]*)', log)
check(bool(m) and '3.3' in m.group(1), 'run 1: class used: ' + (m.group(1) if m else '?'))
bbl_fresh = open(os.path.join(fresh, 'main.bbl')).read()
check(bbl_fresh == open(os.path.join(OUT, 'main.bbl')).read(), 'BibTeX on refs.bib + elsarticle-harv.bst reproduces the shipped main.bbl')
shutil.copyfile(os.path.join(fresh, 'main.pdf'), os.path.join(test, 'run1.pdf'))
pages1, text1, pix1 = compare(os.path.join(test, 'run1.pdf'), 'run1')
check(pages1[0] == pages1[1], 'run 1: page count %d, review build %d' % (pages1[1], pages1[0]))
print('   note run 1: text differs on pages %s, rendering on %d pages (same page breaks). This appears to be a tectonic'
      % (text1 or 'none', len(pix1)))
print('        effect: when its in-process reruns start without an .aux, lines that begin in typewriter type end up about')
print('        0.8 pt further left, which also moves the line breaks in three references. Runs 2 and 3 start from the .aux,')
print('        as each pdfLaTeX pass in Editorial Manager (a new process) does, and reproduce the review build exactly.')
# Run 2 starts from run 1's .aux and .bbl, as every later LaTeX run (and each pdfLaTeX pass in Editorial Manager) does.
r = tectonic(fresh)
check(r.returncode == 0, 'run 2 (from run 1\'s .aux and .bbl): tectonic exit code 0')
log = open(os.path.join(fresh, 'main.log'), errors='replace').read()
check(not re.search(r'undefined|Undefined', log) and 'Rerun to get' not in log, 'run 2: no undefined references, no rerun request')
new_pdf = os.path.join(test, 'run2.pdf'); shutil.copyfile(os.path.join(fresh, 'main.pdf'), new_pdf)
(n_ref, n_new), text_diff, pix_diff = compare(new_pdf, 'run2')
check(n_ref == n_new, 'run 2: page count %d, review build %d' % (n_new, n_ref))
check(not text_diff, 'run 2: extracted text identical on every page' + (' (differs on %s)' % text_diff if text_diff else ''))
check(not pix_diff, 'run 2: rendered pages pixel-identical to the review build at 110 dpi (%d pages)' % n_ref + (' (differ: %s)' % pix_diff if pix_diff else ''))
# Run 3: one TeX pass only (no in-process rerun), the closest tectonic gets to one pdfLaTeX pass.
r = tectonic(fresh, '--reruns', '0')
check(r.returncode == 0, 'run 3 (single TeX pass from the .aux): tectonic exit code 0')
shutil.copyfile(os.path.join(fresh, 'main.pdf'), os.path.join(test, 'run3.pdf'))
(n_ref3, n_new3), text3, pix3 = compare(os.path.join(test, 'run3.pdf'), 'run3')
check(n_ref3 == n_new3 and not text3 and not pix3, 'run 3: identical to the review build (pages, text, pixels)'
      + (' (text differs on %s, pixels on %s)' % (text3, pix3) if (text3 or pix3) else ''))

strict = os.path.join(test, 'strict'); shutil.rmtree(strict, ignore_errors=True); shutil.copytree(OUT, strict)
st = open(os.path.join(strict, 'main.tex')).read().replace('%\\def\\SUBMISSION{1}', '\\def\\SUBMISSION{1}', 1)
open(os.path.join(strict, 'main.tex'), 'w').write(st)
r2 = subprocess.run([TECTONIC, '--chatter', 'minimal', 'main.tex'], cwd=strict, capture_output=True, text=True)
if n_todo:
    check(r2.returncode != 0 and 'Unresolved' in (r2.stdout + r2.stderr),
          'strict switch stops the compilation while %d \\todo items are open' % n_todo)
else:
    check('\n\\def\\SUBMISSION{1}' in open(os.path.join(OUT, 'main.tex')).read() and r2.returncode == 0,
          'no \\todo left: the shipped main.tex is in strict mode (\\def\\SUBMISSION{1}) and compiles')

# ---------------------------------------------------------------- 5. manuscript PDF
if not problems:
    shutil.copyfile(new_pdf, os.path.join(OUT, 'main.pdf'))
    print('5. main.pdf (verified flat build) copied into the folder')
supp = PdfReader(os.path.join(OUT, 'supplement.pdf'))
print('\nFolder contents:')
for f in sorted(os.listdir(OUT)):
    p = os.path.join(OUT, f)
    extra = ''
    if f.endswith('.pdf') and f.startswith(('main', 'supplement')):
        extra = '  %d pages' % len(PdfReader(p).pages)
    print('  %-22s %9d bytes  sha256 %s%s' % (f, os.path.getsize(p), sha(p)[:12], extra))
print('\nopen \\todo items in main.tex: %d' % n_todo)
if not args.testdir:
    shutil.rmtree(test, ignore_errors=True)   # 2026-09-28: remove the scratch renders (disk space); pass --testdir to keep them
    print('scratch directory removed:', test)
print('RESULT:', 'PASS' if not problems else 'FAIL (%d)' % len(problems))
sys.exit(1 if problems else 0)
