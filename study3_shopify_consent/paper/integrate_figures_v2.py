"""Bring the v2 figures (figures/v2/) into the paper folder. Called by build.sh before compiling; safe to re-run.

  1. v1 figure PDFs that are still in figs/ are moved to figs/v1/ (kept, never deleted).
  2. The v2 composites are copied as figs/fig1.pdf ... fig6.pdf and figs/figS1.pdf ... figS9.pdf.
  3. The generated v2 captions (figures/v2/figN/caption_figN.tex, figures/v2/supp/caption_supp.tex) are copied to
     captions/figN.tex and captions/figSN.tex, which main.tex / supplement.tex \\input inside each figure environment.
     The only change is the AI-tool note for the panels drawn in TikZ (v6: Figs. 1a, 2a-c and S1), which the v1 captions
     carried and the manuscript's Section "Use of AI tools" requires; it contains no number.
  4. The supplementary arm table built with Fig. 2 (figures/v5/fig2/tableS_arms.tex) is copied to tables/.
Nothing is typed by hand: numbers stay exactly as the v2 figure scripts rendered them. Captions are edited in the
figure scripts under figures/v2/, never in captions/.
"""
import glob
import os
import re
import shutil

HERE = os.path.dirname(os.path.abspath(__file__))
STUDY = os.path.dirname(HERE)
V2 = os.path.join(STUDY, 'figures', 'v7')   # v7 figures, sciplot skill style, 2026-10-20
FIGS = os.path.join(HERE, 'figs')
CAPS = os.path.join(HERE, 'captions')

V1_FILES = ['fig1_composite.pdf', 'fig2_composite.pdf', 'fig3_prechoice.pdf', 'fig4_blocked_on_paper.pdf', 'fig5_choices.pdf',
            'fig6_reach.pdf', 'figS1_wpm_architecture.pdf', 'figS2_per_cmp.pdf', 'figS3_by_rank.pdf', 'figS4_audit.pdf',
            'figS6_sensitivity.pdf']

AI_MAIN = 'Drawn by figure-generation scripts written with AI assistance (Section~\\ref{sec:method-ai}).'
AI_SUPP = 'Drawn by figure-generation scripts written with AI assistance (Section~\\ref*{M:sec:method-ai} of the main article).'
# v6: Fig. 2's three panels are all TikZ line drawings. v7: Fig. 6a's left part (the code's path, figures/v7/fig6/
# fig6a_path.tex) is a TikZ drawing again, so Fig. 6 carries the note for it.
AI_NOTE = {'fig1': 'Panel~(a): ' + AI_MAIN, 'fig2': 'Panels~(a) to~(c): ' + AI_MAIN,
           'fig6': 'Panel~(a), left: ' + AI_MAIN, 'figS1': AI_SUPP}


def add_note(name, cap):
    """Insert the AI note as the last sentence of the caption (before the closing brace of \\caption{...})."""
    if name not in AI_NOTE:
        return cap
    i = cap.index('\\caption{') + len('\\caption')
    depth, j = 0, i
    while True:
        depth += {'{': 1, '}': -1}.get(cap[j], 0)
        if depth == 0:
            break
        j += 1
    return cap[:j].rstrip() + '\n' + AI_NOTE[name] + cap[j:]


def header(src):
    return ('%% GENERATED by paper/integrate_figures_v2.py from %s (v2 figure caption, rendered by the figure script).\n'
            '%% Do not edit: change the figure script and re-run build.sh.\n' % os.path.relpath(src, STUDY))


def main():
    os.makedirs(os.path.join(FIGS, 'v1'), exist_ok=True)
    os.makedirs(CAPS, exist_ok=True)
    moved = 0
    for f in V1_FILES:
        p = os.path.join(FIGS, f)
        if os.path.exists(p):
            shutil.move(p, os.path.join(FIGS, 'v1', f))
            moved += 1
    # main figures
    for k in range(1, 7):
        name = 'fig%d' % k
        shutil.copyfile(os.path.join(V2, name, name + '.pdf'), os.path.join(FIGS, name + '.pdf'))
        src = os.path.join(V2, name, 'caption_%s.tex' % name)
        body = open(src, encoding='utf-8').read()
        cap = body[body.index('\\caption{'):]            # drop the generator's own header comment
        cap = add_note(name, cap)
        cap.encode('ascii')                                # the flat submission file must be pure ASCII
        open(os.path.join(CAPS, name + '.tex'), 'w', encoding='ascii').write(header(src) + cap.rstrip() + '\n')
    # supplementary figures: caption_supp.tex holds all ten, each after a '% ---- Figure SN (figSN.pdf)' marker
    src = os.path.join(V2, 'supp', 'caption_supp.tex')
    parts = re.split(r'^% ---- Figure (S\d+) \(figS\d+\.pdf\)\s*$', open(src, encoding='utf-8').read(), flags=re.M)
    found = []
    for num, cap in zip(parts[1::2], parts[2::2]):
        name = 'fig' + num
        found.append(num)
        cap = add_note(name, cap.strip())
        open(os.path.join(CAPS, name + '.tex'), 'w', encoding='utf-8').write(header(src) + cap + '\n')
        shutil.copyfile(os.path.join(V2, 'supp', name + '.pdf'), os.path.join(FIGS, name + '.pdf'))
    assert found == ['S%d' % i for i in range(1, 11)], found   # S10: Round 4 pilot (2026-09-27)
    # supplementary arm table built with Fig. 2 (v5: written next to the figure, figures/v5/fig2/tableS_arms.tex, by
    # figures/v5/fig2/scripts/make_table_arms.py; the v4-era copy in figures/tables/ still cites the old Fig. 2d)
    shutil.copyfile(os.path.join(V2, 'fig2', 'tableS_arms.tex'), os.path.join(HERE, 'tables', 'tableS_arms.tex'))
    # the orphan v1 per-vendor figure (its content is Table S5) is not used
    orphan = os.path.join(STUDY, 'figures', 'panels', 'figS5_per_vendor.pdf')
    print('integrate_figures_v2: moved %d v1 files to figs/v1/; copied fig1-6 and figS1-S10 with %d captions; '
          'tables/tableS_arms.tex%s' % (moved, 6 + len(found), '; orphan figures/panels/figS5_per_vendor.pdf still present'
                                        if os.path.exists(orphan) else ''))


if __name__ == '__main__':
    main()
