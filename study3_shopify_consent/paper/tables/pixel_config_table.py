"""Table 1 of the manuscript: Web Pixels Manager configurations declared by the captured main-sample stores.

Input : crawl/pixels.csv (the inline webPixelsConfigList parsed from each store's first usable load)
        analysis/outputs/store_table.csv (defines the 1,362 main-sample stores captured in all three base arms)
Output: paper/tables/pixel_config.json   (every number used in the table and in the text)
        paper/tables/pixel_config_table.tex (LaTeX tabular body, booktabs; generated, do not edit)
Run   : /opt/anaconda3/bin/python3 paper/tables/pixel_config_table.py
"""
import json
import os

import pandas as pd

HERE = os.path.dirname(os.path.abspath(__file__))
STUDY = os.path.dirname(os.path.dirname(HERE))

st = pd.read_csv(os.path.join(STUDY, 'analysis', 'outputs', 'store_table.csv'), dtype={'store_id': str})
main_ids = set(st.loc[st.stratum == 'main', 'store_id'])
px = pd.read_csv(os.path.join(STUDY, 'crawl', 'pixels.csv'), dtype=str).fillna('')
px = px[px.store_id.isin(main_ids)].copy()
px['purposes'] = px.privacyPurposes.apply(lambda s: set(x for x in s.split('|') if x))

out = {'n_main_stores': len(main_ids), 'n_stores_with_config': int(px.store_id.nunique()), 'n_pixels': int(len(px))}
ct = px.groupby(['type', 'runtimeContext']).size()
out['by_type_runtime'] = {f'{t}|{r}': int(v) for (t, r), v in ct.items()}
# Shopify's own entries (app 'shopify-pixel', custom 'shopify-custom-pixel') are on every store; they are
# counted separately so that the 'all pixels' rows describe third-party apps and merchant-added custom pixels.
own = (px.apiClientId == 'shopify-pixel') | (px.pixel_id == 'shopify-custom-pixel')
out['n_shopify_own_entries'] = int(own.sum())
out['shopify_own_runtime'] = {f'{t}|{r}|{p}': int(v) for (t, r, p), v in px[own].groupby(['type', 'runtimeContext', 'privacyPurposes']).size().items()}
app = px[(px.type == 'APP') & ~own]
cus = px[(px.type == 'CUSTOM') & ~own]
for name, d in (('app', app), ('custom', cus)):
    out[f'{name}_n'] = int(len(d))
    out[f'{name}_nopurpose'] = int((d.purposes.apply(len) == 0).sum())
    out[f'{name}_sale'] = int(d.purposes.apply(lambda s: 'SALE_OF_DATA' in s).sum())
    out[f'{name}_marketing'] = int(d.purposes.apply(lambda s: 'MARKETING' in s).sum())
    out[f'{name}_sandboxed'] = int(d.runtimeContext.isin(['STRICT', 'LAX']).sum())
out['stores_with_thirdparty_app'] = int(app.store_id.nunique())
out['stores_with_merchant_custom'] = int(cus.store_id.nunique())
out['stores_with_sandboxed_thirdparty'] = int(pd.concat([app, cus])[lambda d: d.runtimeContext.isin(['STRICT', 'LAX'])].store_id.nunique())
out['stores_with_nopurpose_thirdparty'] = int(pd.concat([app, cus])[lambda d: d.purposes.apply(len) == 0].store_id.nunique())

VEND = [('tiktok', 'TikTok'), ('pinterest', 'Pinterest'), ('snap', 'Snap'), ('meta', 'Meta (Facebook \\& Instagram)'),
        ('google_ads', 'Google \\& YouTube'), ('klaviyo', 'Klaviyo'), ('reddit', 'Reddit'), ('linkedin', 'LinkedIn'),
        ('applovin', 'AppLovin')]
rows = []
for key, label in VEND:
    d = app[app.vendor == key]
    if d.empty:
        continue
    r = dict(vendor=key, label=label, stores=int(d.store_id.nunique()), pixels=int(len(d)))
    rc = d.runtimeContext.value_counts()
    r['runtime'] = rc.index[0]
    r['runtime_share'] = float(rc.iloc[0] / len(d))
    r['share_sale'] = float(d.purposes.apply(lambda s: 'SALE_OF_DATA' in s).mean())
    r['share_marketing'] = float(d.purposes.apply(lambda s: 'MARKETING' in s).mean())
    r['share_none'] = float((d.purposes.apply(len) == 0).mean())
    rows.append(r)
out['vendors'] = rows
json.dump(out, open(os.path.join(HERE, 'pixel_config.json'), 'w'), indent=1)


def pct(x):
    return f'{100 * x:.0f}'


def n(x):
    return f'{x:,}'.replace(',', '{,}')


lines = ['% GENERATED by pixel_config_table.py from crawl/pixels.csv; do not edit by hand.']
for r in rows:
    rt = r['runtime'] if r['runtime_share'] == 1.0 else f"{r['runtime']} ({pct(r['runtime_share'])}\\%)"
    lines.append(f"{r['label']} & {n(r['stores'])} & {rt} & {pct(r['share_marketing'])} & "
                 f"{pct(r['share_sale'])} & {pct(r['share_none'])} \\\\")
lines.append('\\midrule')
lines.append(f"Third-party app pixels ({n(out['app_n'])}) & {n(app.store_id.nunique())} & {pct(out['app_sandboxed'] / out['app_n'])}\\% sandboxed & "
             f"{pct(out['app_marketing'] / out['app_n'])} & {pct(out['app_sale'] / out['app_n'])} & {pct(out['app_nopurpose'] / out['app_n'])} \\\\")
lines.append(f"Merchant custom pixels ({n(out['custom_n'])}) & {n(cus.store_id.nunique())} & LAX (all) & "
             f"{pct(out['custom_marketing'] / out['custom_n'])} & {pct(out['custom_sale'] / out['custom_n'])} & {pct(out['custom_nopurpose'] / out['custom_n'])} \\\\")
open(os.path.join(HERE, 'pixel_config_table.tex'), 'w').write('\n'.join(lines) + '\n')
print(json.dumps({k: v for k, v in out.items() if k != 'vendors'}, indent=1))
for r in rows:
    print(r)
