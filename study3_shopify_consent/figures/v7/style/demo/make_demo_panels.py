"""Matplotlib panels C and D of the v2 style sheet, plus demo_numbers.tex for the TikZ panels.

Every number shown comes from analysis/outputs/stats.json through figstyle.N()/stat(); nothing is typed by hand.
The panels are style demonstrations built on real Study 3 values (they preview Figs 1B and 5A, not replace them).
Outputs go to demo/build/ (panel PDFs, demo_numbers.tex, demo_numbers.csv registry).
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.normpath(os.path.join(HERE, '..')))
import figstyle as fs  # noqa: E402

OUT = os.path.join(HERE, 'build')
os.makedirs(OUT, exist_ok=True)
fs.use()

# layout of the style sheet cells (mm): must equal style_sheet.tex
C_W, C_H = 92, 60
D_W, D_H = 92, 60


def panel_c():
    """Arms by shape (greys), vendors by chip: fig5.a, the 233 working-click stores, equal 10 s windows."""
    fig = fs.panel(C_W, C_H)
    ax = fs.axes_mm(fig, left=24, top=12.5, width=64, height=37)
    rows = ['Any vendor'] + fs.VENDOR_ORDER[:3]     # a style demo: four rows keep the three arms apart
    arms = ['Default', 'Decline', 'GPC']
    off = {'Default': -0.24, 'Decline': 0.0, 'GPC': 0.24}
    for i, v in enumerate(rows):
        for a in arms:
            key = f"fig5/a/{v.replace('/', '~1')}/{a}"
            r = fs.stat(key)
            fs.point(ax, 100 * r['p'], i + off[a], a, ci=(100 * r['lo'], 100 * r['hi']), with_ring=True)
            fs.N(key + '/k'), fs.N(key + '/n')   # register the counts behind every mark
    ax.set_ylim(len(rows) - 0.5, -0.5)
    fs.vendor_labels(ax, range(len(rows)), rows)
    fs.pct_axis(ax, 'x', 0, 60, 20)
    fs.value_grid(ax, 'x')
    ax.axhline(0.5, color=fs.GRID, lw=fs.LW['grid'], zorder=0)
    ax.set_xlabel(f"Stores where a new sandbox fired (%, n = {fs.N('fig5/a/n_clicked')})")
    lg = fs.legend(ax, [fs.handle(a) for a in arms], arms, loc='lower right', ncol=3, bbox_to_anchor=(1.0, 1.02),
                   borderaxespad=0, columnspacing=1.0, handletextpad=0.3)
    fs.save_panel(fig, os.path.join(OUT, 'demo_c.pdf'), title=True)
    return lg


def panel_d():
    """Red = consent failed only: fig1b banner vs no banner; hatch = sandbox only: fig3.c share of ad requests."""
    fig = fs.panel(D_W, D_H)
    # the Fig 1B pattern (type scale v2.1): 9 pt row label above each bar, bar_ci() (white over the bar, ink beyond),
    # and the set's one direct-label pattern 'p% · k of n' (8 pt) just past the CI end
    ax = fs.axes_mm(fig, left=3, top=7, width=64, height=23)
    rows = [(1.0, 'fig1b/banner_fires', 'Banner shown', fs.ACCENT),
            (0.0, 'fig1b/nobanner_fires', 'No banner: no choice offered', fs.GREY_M)]
    half = 0.15
    for y, key, lab, col in rows:
        r = fs.stat(key)
        p, lo, hi = 100 * r['p'], 100 * r['lo'], 100 * r['hi']
        ax.barh(y, p, height=2 * half, left=0, color=col, linewidth=0, zorder=2)
        fs.bar_ci(ax, y, p, lo, hi)
        fs.cat_label(ax, 0, y + half + 0.09, lab, va='bottom')
        fs.direct_label(ax, hi + 2.2, y, fs.PKN(key), va='center')
    ax.set_ylim(-0.4, 1.62)
    ax.set_yticks([])
    ax.spines['left'].set_visible(False)
    fs.pct_axis(ax, 'x', 0, 100, 25)
    ax.set_xlabel(fs.wrap(fs.PRECHOICE_AXIS_TITLE, 'any'))   # the one title of this measure (Figs 1B, 3A, 3B, 4B)

    # hatch = runs in a Shopify sandbox (one 100% bar, Default ad requests by origin)
    bx = fs.axes_mm(fig, left=3, top=48, width=64, height=4.5)
    r = fs.stat('fig3/c/share_sandbox_boot')
    bx.barh(0, 100, height=1, left=0, **fs.light_kw(), zorder=1)
    bx.barh(0, 100 * r['p'], height=1, left=0, **fs.hatch_kw(), zorder=2)
    bx.plot([0, 100 * r['p'], 100 * r['p'], 0, 0], [-0.5, -0.5, 0.5, 0.5, -0.5], color=fs.GREY_D,
            lw=fs.LW['box'], zorder=3, solid_joinstyle='miter')
    bx.set_xlim(0, 100)
    bx.set_ylim(-0.5, 0.5)
    bx.axis('off')
    fs.direct_label(bx, 0, 1.25, f"{fs.PCT('fig3/c/share_sandbox_boot')} of {fs.N('fig3/c/share_sandbox_boot/n')} "
                                 "Default ad requests left from a sandbox", va='baseline')
    fig.text(*fs.fig_xy(fig, 3, 56.5), 'Hatched: sandbox. Outlined light grey: all other origins.',
             fontsize=fs.FS['note'], color=fs.GREY_D, va='baseline')
    fs.save_panel(fig, os.path.join(OUT, 'demo_d.pdf'), title=True)


def numbers_tex():
    """Numbers used inside the TikZ panels (hero specimen), rendered from stats.json."""
    L = ['% demo_numbers.tex -- GENERATED by make_demo_panels.py from analysis/outputs/stats.json; do not edit.',
         f"\\newcommand{{\\demoHero}}{{{fs.PCT('fig1b/banner_fires', 'pct0').replace('%', chr(92) + '%')}}}",
         f"\\newcommand{{\\demoHeroSub}}{{{fs.KN('fig1b/banner_fires')} stores with a banner}}",
         f"\\newcommand{{\\demoKofN}}{{{fs.KN('fig1b/banner_fires')}}}"]
    open(os.path.join(OUT, 'demo_numbers.tex'), 'w').write('\n'.join(L) + '\n')


if __name__ == '__main__':
    fs.reset_registry()
    panel_c()
    panel_d()
    numbers_tex()
    fs.write_registry(os.path.join(OUT, 'demo_numbers.csv'))
    print('wrote demo_c.pdf, demo_d.pdf, demo_numbers.tex, demo_numbers.csv in', OUT)
