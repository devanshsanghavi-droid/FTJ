"""Write numbers.tex: the n-value macros used by the Figure 2 schematics.

Every value is read from a file written by the sampling or analysis code; nothing is
typed by hand. A value whose source does not exist yet is written as the grey
placeholder \\nTBD, so the figure compiles and visibly shows what is still missing.

Sources
  ../../sample/raw/funnel.json        sampling funnel (build_sample.py)
  ../../sample/creator_stratum.csv    purposive creator stratum (build_creator_stratum.py)
  ../../analysis/crawl_funnel.json    OPTIONAL, written by the analysis stage after the crawl:
                                      {"captured_all_arms": <int>, "captured_creator": <int>}

Run:  /opt/anaconda3/bin/python3 make_numbers.py   (then ./build.sh)
"""
import csv
import json
import os

HERE = os.path.dirname(os.path.abspath(__file__))
STUDY = os.path.normpath(os.path.join(HERE, "..", ".."))
FUNNEL = os.path.join(STUDY, "sample", "raw", "funnel.json")
CREATOR = os.path.join(STUDY, "sample", "creator_stratum.csv")
CRAWL = os.path.join(STUDY, "analysis", "crawl_funnel.json")
OUT = os.path.join(HERE, "numbers.tex")


def fmt(n):
    """Thousands separator as in the paper text (200,000)."""
    return f"{int(n):,}"


def main():
    f = json.load(open(FUNNEL))
    pb = f["per_bucket"]
    census = [b for b in pb if pb[b]["sampling_fraction"] == 1.0]
    random_b = [b for b in pb if pb[b]["sampling_fraction"] < 1.0]
    with open(CREATOR, newline="") as fh:
        creator_rows = sum(1 for _ in csv.DictReader(fh))
    crawl = json.load(open(CRAWL)) if os.path.exists(CRAWL) else {}
    stats_fn = os.path.join(STUDY, "analysis", "outputs", "stats.json")
    stats = json.load(open(stats_fn)) if os.path.exists(stats_fn) else {}
    ra = stats.get("fig1b", {}).get("region_allowed")
    fx = crawl.get("funnel_excl", {})

    m = {  # macro name -> (value or None, source)
        "nTrancoList": (f["tranco_list_id"], "funnel.json:tranco_list_id"),
        "nTranco": (f["top_n"], "funnel.json:top_n"),
        "nResolved": (f["domains_with_any_A_record"], "funnel.json:domains_with_any_A_record"),
        "nDNSShopify": (f["dns_flagged_shopify"], "funnel.json:dns_flagged_shopify"),
        "nDrawn": (f["drawn_for_verification"], "funnel.json:drawn_for_verification"),
        "nCensus": (sum(pb[b]["drawn_n"] for b in census), "sum drawn_n over buckets with sampling_fraction 1"),
        "nRandomDrawn": (sum(pb[b]["drawn_n"] for b in random_b), "drawn_n, randomly sampled bucket"),
        "nRandomFrame": (sum(pb[b]["flagged_N"] for b in random_b), "flagged_N, randomly sampled bucket"),
        "nHTTPok": (f["http_200"], "funnel.json:http_200"),
        "nStorefront": (f["verified_live_online_store"], "funnel.json:verified_live_online_store"),
        "nAfterContent": (f["after_content_exclusions"], "funnel.json:after_content_exclusions"),
        "nWithProduct": (f["with_product_url"], "funnel.json:with_product_url"),
        "nSample": (f["sample_after_dedupe"], "funnel.json:sample_after_dedupe"),
        "nCreator": (creator_rows, "rows in creator_stratum.csv"),
        "nCaptured": (crawl.get("captured_all_arms"), "analysis/crawl_funnel.json:captured_all_arms"),
        "nCreatorCaptured": (crawl.get("captured_creator"), "analysis/crawl_funnel.json:captured_creator"),
        "nExclLive": (fx.get("drawn_to_live"), "analysis/crawl_funnel.json:funnel_excl.drawn_to_live"),
        "nExclSample": (fx.get("live_to_sample"), "analysis/crawl_funnel.json:funnel_excl.live_to_sample"),
        "nExclCaptured": (fx.get("sample_to_captured"), "analysis/crawl_funnel.json:funnel_excl.sample_to_captured"),
        "nRepeatPlanned": (crawl.get("repeat_planned"), "analysis/crawl_funnel.json:repeat_planned"),
        "nRepeatOk": (crawl.get("repeat_main_ok"), "analysis/crawl_funnel.json:repeat_main_ok"),
        "nBravePlanned": (crawl.get("brave_planned"), "analysis/crawl_funnel.json:brave_planned"),
        "nBraveOk": (crawl.get("brave_ok"), "analysis/crawl_funnel.json:brave_ok"),
        "pRegionAllowed": (f"{100 * ra['p']:.0f}" if ra else None, "analysis/outputs/stats.json:fig1b.region_allowed.p"),
    }

    lines = [
        "% numbers.tex -- GENERATED by make_numbers.py; do not edit by hand.",
        "% Placeholders (\\nTBD) are filled when the listed source file exists.",
        "\\providecommand{\\nTBD}{{\\color{tbdgrey}[n\\,=\\,?]}}",
    ]
    for name, (val, src) in m.items():
        if val is None:
            body = "\\nTBD"
        elif isinstance(val, str):
            body = val
        else:
            body = fmt(val)
        lines.append(f"\\newcommand{{\\{name}}}{{{body}}}% {src}")
    open(OUT, "w").write("\n".join(lines) + "\n")
    print(open(OUT).read())


if __name__ == "__main__":
    main()
